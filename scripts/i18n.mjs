#!/usr/bin/env node
// Build-time translation tool for the portfolio. No dependencies, Node 18+.
//
//   node scripts/i18n.mjs build        write js/translations.js from i18n/*.json
//   node scripts/i18n.mjs check        validate keys and HTML usage (no network)
//   node scripts/i18n.mjs translate    translate new/changed English text with an API, then build
//   node scripts/i18n.mjs translate --dry-run   show what would be translated
//   node scripts/i18n.mjs init         record the current Arabic as reviewed (first run only)
//
// The translation API key is read from the environment (DEEPL_API_KEY or OPENAI_API_KEY).
// It is never written to any file and never shipped to the browser.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const p = (...a) => path.join(root, ...a);
const config = JSON.parse(fs.readFileSync(p("i18n/config.json"), "utf8"));
const readJson = (f, fallback) => (fs.existsSync(p(f)) ? JSON.parse(fs.readFileSync(p(f), "utf8")) : fallback);
const writeJson = (f, o) => fs.writeFileSync(p(f), JSON.stringify(o, null, 2) + "\n");
const hash = (s) => crypto.createHash("sha1").update(String(s)).digest("hex").slice(0, 12);

const load = () => ({
  en: readJson("i18n/en.json", {}),
  ar: readJson("i18n/ar.json", {}),
  state: readJson("i18n/state.json", {})
});

// state[key] = { en: hash of English text last translated, ar: hash of the Arabic text the tool last wrote or accepted }
// Arabic whose hash no longer matches state.ar was edited by a person, so the tool never overwrites it.

function build() {
  const { en, ar } = load();
  const missing = Object.keys(en).filter((k) => !(k in ar));
  if (missing.length) {
    console.error("Arabic is missing for " + missing.length + " key(s); run translate first:\n  " + missing.join("\n  "));
    process.exit(1);
  }
  const extra = Object.keys(ar).filter((k) => !(k in en));
  if (extra.length) console.warn("Warning: ar.json has keys not in en.json (ignored): " + extra.join(", "));
  const out = {};
  out.en = en;
  out.ar = Object.fromEntries(Object.keys(en).map((k) => [k, ar[k]]));
  const body =
    "/* GENERATED by scripts/i18n.mjs from i18n/en.json and i18n/ar.json. Do not edit by hand. */\n" +
    "window.PORTFOLIO_TRANSLATIONS = " + JSON.stringify(out, null, 2) + ";\n";
  fs.writeFileSync(p("js/translations.js"), body);
  console.log("Wrote js/translations.js (" + Object.keys(en).length + " keys)");
}

function decode(s) {
  return s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, "\u00a0");
}

function check() {
  const { en, ar } = load();
  let errors = 0;
  const fail = (m) => { console.error("ERROR: " + m); errors++; };
  for (const k of Object.keys(en)) if (!(k in ar)) fail("missing Arabic for " + k);
  for (const k of Object.keys(ar)) if (!(k in en)) fail("Arabic key not in en.json: " + k);
  const html = fs.readFileSync(p("index.html"), "utf8");
  const used = new Set();
  // data-i18n="key" and data-i18n-<attribute>="key"; data-i18n-attr and data-i18n-text are options, not keys
  for (const m of html.matchAll(/data-i18n(-(?!attr=|text=)[a-z-]+)?="([^"]+)"/g)) used.add(m[2]);
  for (const k of used) if (!(k in en)) fail("index.html uses unknown key " + k);
  const jsText = ["custom.js", "submit.js", "language.js"].map((f) => fs.readFileSync(p("js", f), "utf8")).join("\n");
  for (const k of Object.keys(en)) {
    if (!used.has(k) && !jsText.includes('"' + k + '"') && !jsText.includes("'" + k + "'")) console.warn("Note: key not used in index.html or scripts: " + k);
  }
  // Warn only: visible default text in the HTML should match English (it is the no-JS / crawler fallback).
  let drift = 0;
  for (const m of html.matchAll(/<(\w+)([^>]*?)data-i18n="([^"]+)"([^>]*)>([^<]*)</g)) {
    const attrs = m[2] + m[4];
    if (/data-i18n-attr=/.test(attrs) && !/data-i18n-text=/.test(attrs)) continue;
    const key = m[3];
    if (key in en && decode(m[5]).trim() !== en[key].trim()) {
      drift++;
      console.warn("Note: HTML fallback text differs from en.json for " + key);
    }
  }
  const gen = fs.existsSync(p("js/translations.js")) ? fs.readFileSync(p("js/translations.js"), "utf8") : "";
  const expected = (() => {
    const out = { en, ar: Object.fromEntries(Object.keys(en).map((k) => [k, ar[k]])) };
    return "/* GENERATED by scripts/i18n.mjs from i18n/en.json and i18n/ar.json. Do not edit by hand. */\n" +
      "window.PORTFOLIO_TRANSLATIONS = " + JSON.stringify(out, null, 2) + ";\n";
  })();
  if (gen !== expected) fail("js/translations.js is out of date; run: node scripts/i18n.mjs build");
  console.log(errors ? errors + " error(s)" : "OK: " + Object.keys(en).length + " keys, " + used.size + " used in HTML" + (drift ? ", " + drift + " HTML fallback note(s)" : ""));
  process.exit(errors ? 1 : 0);
}

function pending({ en, ar, state }) {
  const todo = [];
  for (const k of Object.keys(en)) {
    const s = state[k];
    if (!(k in ar) || ar[k] === "") { todo.push([k, "new"]); continue; }
    if (!s) continue; // existing Arabic with no record: treated as reviewed, never overwritten
    const edited = hash(ar[k]) !== s.ar;
    if (edited) continue; // a person edited it
    if (hash(en[k]) !== s.en) todo.push([k, "english changed"]);
  }
  return todo;
}

function init() {
  const { en, ar, state } = load();
  for (const k of Object.keys(en)) {
    if (k in ar && !state[k]) state[k] = { en: hash(en[k]), ar: hash(ar[k]) };
  }
  writeJson("i18n/state.json", state);
  console.log("Recorded " + Object.keys(state).length + " keys in i18n/state.json");
}

const protect = (text) => {
  const terms = config.preserveTerms || [];
  const map = [];
  let t = text;
  terms.forEach((term, i) => {
    const token = "{{T" + i + "}}";
    if (t.includes(term)) { t = t.split(term).join(token); map.push([token, term]); }
  });
  return [t, (r) => map.reduce((acc, [tok, term]) => acc.split(tok).join(term), r)];
};

async function deepl(texts) {
  const key = process.env.DEEPL_API_KEY;
  if (!key) throw new Error("Set DEEPL_API_KEY (or use provider openai).");
  const base = process.env.DEEPL_API_URL || (key.endsWith(":fx") ? "https://api-free.deepl.com" : "https://api.deepl.com");
  const res = await fetch(base + "/v2/translate", {
    method: "POST",
    headers: { Authorization: "DeepL-Auth-Key " + key, "Content-Type": "application/json" },
    body: JSON.stringify({ text: texts, source_lang: "EN", target_lang: "AR", tag_handling: "xml", ignore_tags: ["x"],
      preserve_formatting: true })
  });
  if (!res.ok) throw new Error("DeepL error " + res.status + ": " + (await res.text()).slice(0, 200));
  const data = await res.json();
  return data.translations.map((t) => t.text);
}

async function openai(texts) {
  const key = process.env.OPENAI_API_KEY;
  if (!key) throw new Error("Set OPENAI_API_KEY (or use provider deepl).");
  const base = process.env.OPENAI_API_URL || "https://api.openai.com";
  const res = await fetch(base + "/v1/chat/completions", {
    method: "POST",
    headers: { Authorization: "Bearer " + key, "Content-Type": "application/json" },
    body: JSON.stringify({
      model: process.env.I18N_OPENAI_MODEL || config.openaiModel,
      temperature: 0.2,
      response_format: { type: "json_object" },
      messages: [
        { role: "system", content: "You translate website text from English to Modern Standard Arabic for a developer portfolio. Keep the tone natural and professional. Keep tokens like {{T0}} unchanged. Return JSON: {\"translations\": [..]} with exactly one string per input, same order." },
        { role: "user", content: JSON.stringify({ texts }) }
      ]
    })
  });
  if (!res.ok) throw new Error("OpenAI error " + res.status + ": " + (await res.text()).slice(0, 200));
  const data = await res.json();
  const arr = JSON.parse(data.choices[0].message.content).translations;
  if (!Array.isArray(arr) || arr.length !== texts.length) throw new Error("OpenAI returned an unexpected number of translations");
  return arr;
}

async function translate(dry) {
  const data = load();
  const todo = pending(data);
  if (!todo.length) { console.log("Nothing to translate."); build(); return; }
  console.log(todo.length + " key(s) to translate:");
  todo.forEach(([k, why]) => console.log("  " + k + " (" + why + ")"));
  if (dry) return;
  const provider = process.env.I18N_PROVIDER || config.provider;
  const prepared = todo.map(([k]) => protect(data.en[k]));
  const results = [];
  for (let i = 0; i < prepared.length; i += 40) {
    const batch = prepared.slice(i, i + 40).map((x) => x[0]);
    results.push(...(provider === "openai" ? await openai(batch) : await deepl(batch)));
  }
  todo.forEach(([k], i) => {
    const text = prepared[i][1](results[i]);
    data.ar[k] = text;
    data.state[k] = { en: hash(data.en[k]), ar: hash(text) };
  });
  writeJson("i18n/ar.json", Object.fromEntries(Object.keys(data.en).map((k) => [k, data.ar[k]])));
  writeJson("i18n/state.json", data.state);
  console.log("Updated i18n/ar.json and i18n/state.json. Review the new Arabic, then commit.");
  build();
}

const [cmd, flag] = process.argv.slice(2);
if (cmd === "build") build();
else if (cmd === "check") check();
else if (cmd === "init") init();
else if (cmd === "translate") translate(flag === "--dry-run").catch((e) => { console.error(e.message); process.exit(1); });
else { console.error("Usage: node scripts/i18n.mjs build | check | init | translate [--dry-run]"); process.exit(1); }
